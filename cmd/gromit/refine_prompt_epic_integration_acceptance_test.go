// Mock types for testing

type mockAgentForPromptTest struct {
	receivedPromptPath string
}

func (m *mockAgentForPromptTest) Launch(promptPath string) error {
	m.receivedPromptPath = promptPath
	return nil
}

type mockResolverForPromptTest struct {
	agent *mockAgentForPromptTest
}

func (m *mockResolverForPromptTest) Resolve(phase string, flagOverride string, choosePicker bool) (pipeline.Agent, error) {
	return m.agent, nil
}

type backlogAdapterForTest struct {
	file *backlog.File
}

func (b *backlogAdapterForTest) List() ([]*pipeline.Idea, error) {
	if b.file == nil {
		return []*pipeline.Idea{}, nil
	}
	ideas, err := b.file.List()
	if err != nil {
		return nil, err
	}
	result := make([]*pipeline.Idea, len(ideas))
	for i, idea := range ideas {
		result[i] = &pipeline.Idea{
			ID:       idea.ID,
			Text:     idea.Text,
			Type:     idea.Type,
			Context:  idea.Context,
			Status:   idea.Status,
			SpecName: idea.SpecName,
		}
	}
	return result, nil
}

func (b *backlogAdapterForTest) Get(id string) (*pipeline.Idea, error) {
	if b.file == nil {
		return nil, nil
	}
	idea, err := b.file.Get(id)
	if err != nil || idea == nil {
		return nil, err
	}
	return &pipeline.Idea{
		ID:       idea.ID,
		Text:     idea.Text,
		Type:     idea.Type,
		Context:  idea.Context,
		Status:   idea.Status,
		SpecName: idea.SpecName,
	}, nil
}

func (b *backlogAdapterForTest) Add(item *pipeline.Idea) error {
	if b.file == nil {
		return nil
	}
	return b.file.Add(&backlog.Idea{
		ID:       item.ID,
		Text:     item.Text,
		Type:     item.Type,
		Context:  item.Context,
		Status:   item.Status,
		SpecName: item.SpecName,
	})
}

func (b *backlogAdapterForTest) Update(id string, fn func(*pipeline.Idea)) error {
	if b.file == nil {
		return nil
	}
	return b.file.Update(id, func(idea *backlog.Idea) {
		pipelineIdea := &pipeline.Idea{
			ID:       idea.ID,
			Text:     idea.Text,
			Type:     idea.Type,
			Context:  idea.Context,
			Status:   idea.Status,
			SpecName: idea.SpecName,
		}
		fn(pipelineIdea)
		idea.Status = pipelineIdea.Status
		idea.SpecName = pipelineIdea.SpecName
	})
}
