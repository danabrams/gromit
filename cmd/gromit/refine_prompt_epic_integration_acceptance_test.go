// TestPipelineRefinePrompt_WithEpicContext tests that buildRefinePrompt includes epic context when appropriate
func TestPipelineRefinePrompt_WithEpicContext(t *testing.T) {
	// Expected failure: pipeline.buildRefinePrompt does not yet detect epics or inject epic context
	// Expected behavior: When a backlog item references an epic via context field,
	// buildRefinePrompt should detect it and include epic document + sibling specs
	//
	// This test verifies acceptance criteria:
	// 1. When backlog context contains known epic ID, prompt includes full epic document and sibling spec summaries
	// 4. Prompt instructs Claude to set epic: <id> in frontmatter
	// 5. Detection handles substring matching

	tmpDir := t.TempDir()
	gromitDir := filepath.Join(tmpDir, ".gromit")
	epicsDir := filepath.Join(gromitDir, "epics")
	specsDir := filepath.Join(gromitDir, "specs")

	if err := os.MkdirAll(epicsDir, 0755); err != nil {
		t.Fatalf("Failed to create epics dir: %v", err)
	}
	if err := os.MkdirAll(specsDir, 0755); err != nil {
		t.Fatalf("Failed to create specs dir: %v", err)
	}

	// Create epic file
	epicContent := `---
epic_id: payment-integration
created: 2026-02-11
---

# Payment Integration Epic

This epic covers all payment processing features.

## Vision

Enable multiple payment methods for customers.
`
	epicPath := filepath.Join(epicsDir, "payment.md")
	if err := os.WriteFile(epicPath, []byte(epicContent), 0644); err != nil {
		t.Fatalf("Failed to write epic file: %v", err)
	}

	// Create sibling spec
	siblingContent := `---
id: payment-api
epic: payment-integration
created: 2026-02-11
---

# Payment API Spec

## Acceptance Criteria

- API accepts payment requests
- API returns transaction ID on success
`
	siblingPath := filepath.Join(specsDir, "payment-api.md")
	if err := os.WriteFile(siblingPath, []byte(siblingContent), 0644); err != nil {
		t.Fatalf("Failed to write sibling spec: %v", err)
	}

	// Create backlog with idea referencing epic
	bf, err := backlog.NewFile(gromitDir)
	if err != nil {
		t.Fatalf("Failed to create backlog file: %v", err)
	}

	idea := &backlog.Idea{
		ID:      "idea-test-1",
		Text:    "Add payment confirmation page",
		Type:    "feature",
		Context: "Part of payment-integration epic",
		Status:  "pending",
	}
	if err := bf.Add(idea); err != nil {
		t.Fatalf("Failed to add idea: %v", err)
	}

	// Create pipeline
	cfg := &config.Config{
		Paths: config.PathsConfig{
			GromitDir: gromitDir,
			Specs:     specsDir,
		},
	}

	mockAgent := &mockAgentForPromptTest{}
	mockResolver := &mockResolverForPromptTest{agent: mockAgent}
	mockBacklog := &backlogAdapterForTest{file: bf}

	deps := &pipeline.Deps{
		AgentResolver: mockResolver,
		BacklogClient: mockBacklog,
	}

	paths := &pipeline.Paths{
		GromitDir: gromitDir,
		SpecsDir:  specsDir,
	}

	p := pipeline.New(deps, paths)

	// Load idea with context
	loadedIdea, err := bf.Get("idea-test-1")
	if err != nil {
		t.Fatalf("Failed to load idea: %v", err)
	}

	ideaText := loadedIdea.Text
	if loadedIdea.Context != "" {
		ideaText = loadedIdea.Text + "\n\nContext: " + loadedIdea.Context
	}

	// Build the prompt using the pipeline's internal buildRefinePrompt method
	// Since it's private, we need to invoke it indirectly by calling a method that uses it
	// The Refine method calls buildRefinePrompt internally and passes it to the agent
	// We can capture what prompt was generated by checking what the mock agent received

	input := pipeline.RefineInput{
		IdeaID: "idea-test-1",
	}

	// Call Refine - it will invoke buildRefinePrompt and pass prompt to agent
	_, err = p.Refine(t.Context(), input)
	// We expect an error because our mock agent doesn't actually do anything
	// but we can still check what prompt it received

	// Get the prompt that was passed to the agent
	prompt := mockAgent.receivedPromptPath
	if prompt == "" {
		t.Fatal("No prompt was passed to agent")
	}

	// Read the prompt file
	promptContent, err := os.ReadFile(prompt)
	if err != nil {
		t.Fatalf("Failed to read prompt file: %v", err)
	}
	promptStr := string(promptContent)

	// Verify epic context section is present
	if !strings.Contains(promptStr, "## Epic Context") {
		t.Error("Prompt should contain '## Epic Context' section header")
	}

	// Verify epic document content is included
	if !strings.Contains(promptStr, "# Payment Integration Epic") {
		t.Error("Prompt should contain epic title from document")
	}
	if !strings.Contains(promptStr, "Enable multiple payment methods for customers") {
		t.Error("Prompt should contain epic vision from document")
	}

	// Verify frontmatter instruction
	if !strings.Contains(promptStr, "Include `epic: payment-integration` in the spec frontmatter") {
		t.Error("Prompt should instruct Claude to add epic field to frontmatter")
	}

	// Verify sibling specs section
	if !strings.Contains(promptStr, "### Sibling Specs") {
		t.Error("Prompt should contain '### Sibling Specs' section")
	}

	// Verify sibling spec is summarized
	if !strings.Contains(promptStr, "**Payment API Spec**") {
		t.Error("Prompt should contain sibling spec title")
	}
	if !strings.Contains(promptStr, "(`payment-api`)") {
		t.Error("Prompt should contain sibling spec ID")
	}
	if !strings.Contains(promptStr, "API accepts payment requests") {
		t.Error("Prompt should contain sibling acceptance criteria")
	}
	if !strings.Contains(promptStr, "API returns transaction ID on success") {
		t.Error("Prompt should contain sibling acceptance criteria")
	}

	// Verify epic section appears between idea and specs directory
	ideaIndex := strings.Index(promptStr, "Add payment confirmation page")
	epicIndex := strings.Index(promptStr, "## Epic Context")
	specsIndex := strings.Index(promptStr, "Specs directory:")

	if ideaIndex == -1 || epicIndex == -1 || specsIndex == -1 {
		t.Fatal("Prompt missing required sections for ordering check")
	}

	if !(ideaIndex < epicIndex && epicIndex < specsIndex) {
		t.Error("Epic Context section should appear between idea text and specs directory line")
	}
}

